function daysAgo(days: number): string {
    const date = new Date();
    date.setDate(date.getDate() - days);
    date.setHours(11, 0, 0, 0);
    return date.toISOString();
}

function daysAhead(days: number): string {
    const date = new Date();
    date.setDate(date.getDate() + days);
    date.setHours(11, 0, 0, 0);
    return date.toISOString();
}

