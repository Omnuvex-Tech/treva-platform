/**
 * The eight-row Finance extract (1173:16374).
 *
 * The artboard repeats one placeholder down every column — a phone number sits
 * under the unit-code heading — so the values here are plausible rather than
 * copied. What IS copied is the shape: eight rows, no pager, and a "Page Link"
 * out to the Finance section that owns the full ledger.
 */
function financeRowsFor(projectName: string): ProjectFinanceRow[] {
    return Array.from({ length: 8 }, (_, index) => {
        const listingPrice = 180_000 + index * 12_500;
        const salesPrice = listingPrice - 4_000;
        const received = Math.round(salesPrice * (0.3 + index * 0.05));

        return {
            id: `fin_${index + 1}`,
            projectName,
            unitCode: `A ${21 + index} - 0${(index % 4) + 1}`,
            listingPrice,
            salesPrice,
            received,
            paid: Math.round(received * 0.9),
            remaining: salesPrice - received,
            salesDate: daysAgo(9 + index * 6),
        };
    });
}

function inMonths(months: number): string {
    const date = new Date();
    date.setMonth(date.getMonth() + months);
    date.setDate(1);
    return date.toISOString();
}

